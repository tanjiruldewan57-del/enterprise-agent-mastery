"""
Enterprise Agent State Definition (TypedDict with Reducer Channels)
===================================================================
Architecture: Formal State Contract for LangGraph State Machine
Compliance: Type-Safe State Propagation & Immutable Audit Accumulator
"""

import operator
from typing import TypedDict, Annotated, List, Dict, Any, Optional


class AttemptRecord(TypedDict):
    """Schema for individual self-healing trial records."""
    step: str                          # Node name (e.g. 'generator', 'executor', 'reflector')
    generated_sql: Optional[str]       # SQL attempted in this cycle
    error: Optional[str]               # Error encountered (if any)
    is_valid: bool                     # Whether AST and DB validation passed
    execution_time_ms: float           # Execution duration in milliseconds


class AgentState(TypedDict):
    """
    Master Enterprise State Schema.
    
    Channels:
      - Default Overwrite: Variables that represent the 'current' instant.
      - Annotated[..., operator.add]: Cumulative channel preserving complete history.
    """
    # 1. Ingress & User Intent Channels (Overwrite)
    user_query: str                    # Original raw user question
    sanitized_query: str               # Output after Prompt Injection Shield normalization
    
    # 2. Execution & Generation Channels (Overwrite)
    current_sql: str                   # Latest SQL generated by generator/reflector
    sql_results: Optional[List[Dict[str, Any]]] # Result set returned from DB query
    is_success: bool                   # True if execution succeeded cleanly
    error_message: Optional[str]       # Latest error message, if failed
    
    # 3. Guardrail & Control Flow Channels (Overwrite)
    execution_status: str              # 'PENDING', 'SUCCESS', 'FAILED_MAX_RETRIES', 'BLOCKED_GUARDRAIL'
    retry_count: int                   # Current retry count (0, 1, 2...)
    max_retries: int                   # Hard ceiling (e.g. 3) to prevent runaway execution
    
    # 4. Cumulative Audit Channel (REDUCER - operator.add)
    # This channel NEVER overwrites; every node update appends its attempt record!
    attempt_history: Annotated[List[Dict[str, Any]], operator.add]
